import { useAiDrafts, useAiFeature } from '@/api/hooks/useAi';
import { SafeText } from './AiShared';

/** Shows the accepted AI summary only. Renders nothing when AI is off, no summary was accepted, or access is denied. */
export function TldrBlock({ contentId }: { contentId: number }) {
  const { visible } = useAiFeature('editorial');
  const { data } = useAiDrafts('article', contentId, 'summary', visible);
  const accepted = (data ?? []).find((d) => d.status === 'accepted');
  if (!visible || !accepted) return null;
  const tldr = String(accepted.payload.tldr ?? '');
  if (!tldr) return null;
  const takeaways = Array.isArray(accepted.payload.takeaways) ? (accepted.payload.takeaways as string[]) : [];
  return (
    <aside aria-label="TL;DR" className="my-4 rounded-lg border bg-muted/40 p-4">
      <h2 className="mb-1 text-sm font-semibold">TL;DR</h2>
      <SafeText text={tldr} className="text-sm" />
      {takeaways.length > 0 && <ul className="mt-2 list-disc pl-5 text-sm">{takeaways.map((t, i) => <li key={i}>{t}</li>)}</ul>}
      <p className="mt-2 text-xs text-muted-foreground">Summary generated by AI and approved by an editor.</p>
    </aside>
  );
}
